from pathlib import PurePosixPath
import re


# ---------------------- Folders that are never indexed -----------------------
# Dependencies, caches and build output that are almost never real source folders.
# They are huge, not written by the repository owner and would drown the real code
# in search results, so they are skipped at any depth (e.g. frontend/dist/)
ALWAYS_EXCLUDED_DIRECTORIES = {
    ".git", "node_modules", "bower_components", "__pycache__", ".venv", "venv",
    "site-packages", ".tox", ".mypy_cache", ".pytest_cache", ".ruff_cache", ".gradle",
    ".next", ".nuxt", "dist", "coverage",
}

# These names are also used for real source folders (src/build/ in the pypa/build
# package, cmd/build/ in Go projects), so they are only skipped at the repository root
ROOT_ONLY_EXCLUDED_DIRECTORIES = {"build", "out", "target", "vendor"}

# ---------------------- Files that are never indexed -------------------------
# Lockfiles are generated by package managers and can be thousands of lines long
LOCKFILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "uv.lock",
    "poetry.lock", "Pipfile.lock", "Cargo.lock", "composer.lock", "Gemfile.lock",
    "go.sum", "flake.lock",
}

# Checked with endswith() so multi-part suffixes like ".min.js" work
GENERATED_SUFFIXES = (".min.js", ".min.css", ".map", ".pb.go", "_pb2.py", "_pb2_grpc.py")

BINARY_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".ico", ".webp", ".svg", ".pdf", ".zip",
    ".gz", ".tar", ".tgz", ".7z", ".rar", ".jar", ".class", ".exe", ".dll", ".so",
    ".dylib", ".pyc", ".whl", ".woff", ".woff2", ".ttf", ".otf", ".eot", ".mp3", ".mp4",
    ".wav", ".mov", ".sqlite", ".db", ".parquet", ".npy", ".pkl",
}

# Data rather than code. Notebooks are JSON with embedded (often base64) outputs
DATA_EXTENSIONS = {".csv", ".tsv", ".ipynb"}

# Files that often contain secrets. They should never be sent to an embedding model
CREDENTIAL_NAMES = {
    ".env", ".envrc", ".netrc", ".npmrc", ".pypirc", ".htpasswd", ".dockercfg",
    "id_rsa", "id_dsa", "id_ecdsa", "id_ed25519", "credentials", "credentials.json",
}
CREDENTIAL_EXTENSIONS = {".pem", ".key", ".p12", ".pfx", ".keystore", ".jks", ".tfvars"}

# Templates like .env.example only hold variable names, so the .env rule skips them
ENV_TEMPLATE_SUFFIXES = (".example", ".sample", ".template")

PRIVATE_KEY_MARKER = re.compile(rb"-----BEGIN (?:[A-Z]+ )?PRIVATE KEY-----")

# A generated file says so in its header. Plain words like "auto-generated" are
# not enough, because normal code mentions them too ("helpers for auto-generated IDs")
GENERATED_HEADER = re.compile(
    r"@generated"
    r"|code generated .* do not edit"
    r"|(?:this|the) file (?:is|was|has been) (?:auto-?|automatically )?generated"
    r"|do not edit (?:this file|manually|by hand)",
    re.IGNORECASE,
)


# ---------------------- Checks the folders of a path -------------------------
# Returns the excluded folder, e.g. "frontend/node_modules/", so it can be recorded
# once instead of once for every file inside it
def get_excluded_directory(path: str) -> str | None:
    folders = PurePosixPath(path).parts[:-1]

    for depth, folder in enumerate(folders):
        is_root_build_output = depth == 0 and folder in ROOT_ONLY_EXCLUDED_DIRECTORIES
        if folder in ALWAYS_EXCLUDED_DIRECTORIES or is_root_build_output:
            return "/".join(folders[: depth + 1]) + "/"

    return None


# ---------------------- Checks a file path before the file is read -----------
# Returns the reason a file is excluded, or None if it should be kept.
# Only the path is used, so excluded files are never read from the archive
def get_path_exclusion_reason(path: str) -> str | None:
    file_path = PurePosixPath(path)
    name = file_path.name
    lower_name = name.lower()
    extension = file_path.suffix.lower()

    if name in LOCKFILES:
        return "lockfile"

    # Only .env templates are allowed. "server.key.template" or "id_rsa.sample" could
    # still be a real key, so the template suffix is removed before the other checks
    is_env_template = lower_name.startswith(".env") and lower_name.endswith(ENV_TEMPLATE_SUFFIXES)
    base_name = lower_name.removesuffix(PurePosixPath(lower_name).suffix) if lower_name.endswith(ENV_TEMPLATE_SUFFIXES) else lower_name
    base_extension = PurePosixPath(base_name).suffix

    is_env_file = base_name.startswith(".env.") or base_name == ".env"
    is_service_account = base_name.startswith("service-account") and base_extension == ".json"
    is_credential = (
        base_name in CREDENTIAL_NAMES
        or is_env_file
        or is_service_account
        or base_extension in CREDENTIAL_EXTENSIONS
    )
    if is_credential and not is_env_template:
        return "may contain credentials"

    if lower_name.endswith(GENERATED_SUFFIXES):
        return "generated file"

    if extension in BINARY_EXTENSIONS:
        return "binary file"

    if extension in DATA_EXTENSIONS:
        return "data file"

    return None


# ---------------------- Checks the content after the file is read ------------
def get_content_exclusion_reason(content: bytes) -> str | None:
    # Text files don't contain NUL bytes, so this catches binaries with a text extension
    if b"\x00" in content[:8000]:
        return "binary file"

    # A private key pasted into a normal file (e.g. a test fixture in a .py file)
    if PRIVATE_KEY_MARKER.search(content):
        return "may contain credentials"

    header = "\n".join(content[:2000].decode("utf-8", errors="ignore").splitlines()[:5])
    if GENERATED_HEADER.search(header):
        return "generated file"

    # Minified code puts everything on a few very long lines
    lines = content.count(b"\n") + 1
    if len(content) > 5000 and len(content) / lines > 500:
        return "minified or generated file"

    return None
