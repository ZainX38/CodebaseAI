@pytest.mark.parametrize("path", ["certs/server.key.template", "ssh/id_rsa.sample", "config/credentials.json.example"])
def test_templates_only_skip_the_env_rule(path):
    assert get_path_exclusion_reason(path) == "may contain credentials"


def test_content_with_nul_bytes_is_binary():
    assert get_content_exclusion_reason(b"abc\x00def") == "binary file"


def test_private_key_inside_a_normal_file_is_excluded():
    content = b'TEST_KEY = """\n-----BEGIN RSA PRIVATE KEY-----\nMIIEow...\n"""\n'

    assert get_content_exclusion_reason(content) == "may contain credentials"


@pytest.mark.parametrize(
    "header",
    [
        b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n",
        b"# @generated by a tool\nx = 1\n",
        b"/* This file was automatically generated. */\n",
        b"# Do not edit this file, run make instead\n",
    ],
)
def test_content_marked_as_generated_is_excluded(header):
    assert get_content_exclusion_reason(header) == "generated file"


@pytest.mark.parametrize(
    "header",
    [
        b'"""Helpers for auto-generated IDs."""\n',
        b"# The client returns autogenerated tokens\n",
    ],
)
def test_code_that_only_mentions_generated_things_is_kept(header):
    assert get_content_exclusion_reason(header) is None


def test_minified_content_is_excluded():
    assert get_content_exclusion_reason(b"var a=1;" * 1000) == "minified or generated file"


def test_normal_source_is_kept():
    assert get_content_exclusion_reason(b"def add(a, b):\n    return a + b\n") is None


def test_extract_applies_the_filters_and_keeps_every_reason():
    extracted = extract_files(make_tarball({
        "src/app.py": b"x = 1\n",
        "node_modules/left-pad/index.js": b"module.exports = 1\n",
        "node_modules/left-pad/package.json": b"{}\n",
        "package-lock.json": b"{}\n",
        "data.txt": b"\x00\x01\x02",
    }))

    assert extracted.files == {"src/app.py": "x = 1\n"}
    # node_modules/ is recorded once for the folder, not once per file
    assert extracted.excluded == {
        "node_modules/": "dependencies, build output or cache",
        "package-lock.json": "lockfile",
        "data.txt": "binary file",
    }
