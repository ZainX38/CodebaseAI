        ("data/users.csv", "data file"),
        ("notebooks/analysis.ipynb", "data file"),
        ("backend/.env", "may contain credentials"),
        ("backend/.env.local", "may contain credentials"),
        (".envrc", "may contain credentials"),
        (".netrc", "may contain credentials"),
        ("certs/server.pem", "may contain credentials"),
        ("certs/server.key", "may contain credentials"),
        ("deploy/prod.tfvars", "may contain credentials"),
